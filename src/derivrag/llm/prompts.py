"""提示词模板。

生成侧的核心是**强引用约束**，这是降低幻觉的主要抓手：
只依据给定条款作答、必须给出文号与条号、没有依据就明确说不知道。
金融条款问答里，一个编造的保证金公式比"我不知道"危害大得多。
"""

from __future__ import annotations

# =====================================================================
# 生成
# =====================================================================

ANSWER_SYSTEM = """你是衍生品交易条款检索助手，服务对象是期权业务人员与投资者。

回答规则（必须严格遵守）：
1. 只能依据【参考条款】中的内容作答，不得使用你的先验知识补充或推测。
2. 每一个事实性陈述后面都要标注来源编号，形如 [1]、[2]。
3. 涉及具体数值（合约单位、保证金比例、行权价格间距、时间点等）时，
   必须逐字引用原文数值，不得换算、取整或改写。
4. 如果【参考条款】不足以回答问题，直接说明"根据现有条款无法确定"，
   并指出还需要哪类文件。禁止编造条款号、文号或数值。
5. 若不同交易所的规定不一致，分别说明各自的规定并点明差异。
6. 用简洁的中文回答，先给结论，再给依据。"""

ANSWER_USER = """【参考条款】
{context}

【问题】
{question}

请依据上述条款作答，并标注来源编号。"""


ANSWER_NO_CONTEXT = """根据现有条款库未能检索到与该问题相关的内容，无法作答。

建议：
- 换用条款中的正式术语重新提问（例如用"合约单位"而非"一手多少份"）
- 或指明具体的交易所与品种（如"上交所 50ETF 期权"）"""


# =====================================================================
# HyDE —— 假设性文档嵌入
# =====================================================================
#
# 解决的是查询与文档的**语义不对称**：用户问"期权到期后没行权会怎样"，
# 而条款原文写的是"到期未行权的合约作废，权利方损失权利金"。
# 两者用词几乎不重叠，稠密检索容易漏。
#
# HyDE 的做法是先让 LLM 生成一段"假如答案存在，它应该长什么样"的文本，
# 再用这段文本去检索 —— 它天然使用条款的术语和句式，与真实条款的
# 向量距离比原始口语化问题近得多。
#
# 注意：假设文档只用于**检索**，绝不进入最终答案的上下文，
# 否则模型会把自己编的内容当成依据。

HYDE_SYSTEM = """你是交易所规则文本的撰写者。用户会给你一个关于期权/衍生品条款的问题，
请你写出一段"看起来像是从交易所业务规则里摘出来的"条款原文，来回答这个问题。

要求：
- 使用交易所规则的正式书面语与专业术语（如"合约标的""行权价格间距""义务仓""维持保证金"）
- 采用条款体裁，可以用"第X条"开头
- 长度控制在 100-200 字
- 不要说"我不知道"，也不要解释你在做什么，直接输出条款文本
- 内容准确与否不重要，重要的是术语和句式要像真实条款

注意：这段文本仅用于检索匹配，不会展示给用户。"""

HYDE_USER = """问题：{question}

请写出对应的条款原文："""


# =====================================================================
# 多轮查询重写
# =====================================================================
#
# 多轮对话里用户会大量使用省略和指代：
#   Q1: 50ETF期权的到期日是什么时候？
#   Q2: 那深证100ETF呢？          <- 省略了"期权的到期日"
#   Q3: 这两个有什么区别？          <- "这两个"指代前两轮的主体
# 直接拿 Q2/Q3 去检索必然失败。重写模块负责把它们补全成独立可检索的问题。

REWRITE_SYSTEM = """你负责把多轮对话中的追问改写成一个**独立完整、可直接用于检索**的问题。

规则：
- 补全所有省略成分和指代（"那"、"这个"、"它"、"这两个"等）
- 保留原问题的意图，不要额外添加用户没问的内容
- 使用条款中的正式术语
- 只输出改写后的问题本身，不要任何解释、前缀或引号
- 如果当前问题本身已经完整，原样输出"""

REWRITE_USER = """【历史对话】
{history}

【当前问题】
{question}

改写后的独立问题："""


# =====================================================================
# QA 自动挖掘
# =====================================================================
#
# span-grounding 是这里的关键约束：要求答案必须是源条款的**连续子串**，
# 生成后再用字符串包含做硬校验，不满足的直接丢弃。
# 这样挖出来的 QA 对天然零幻觉，"自动挖掘的结构化 QA 数据集"这句话
# 才站得住脚。

QA_MINE_SYSTEM = """你负责从交易所条款原文中提取问答对，用于构建检索评测集。

严格要求：
1. 问题必须能**仅凭这一条条款**回答，不依赖任何外部知识。
2. 答案必须是条款原文中**一段连续的原始文字**，逐字复制，不得改写、
   概括、补字或调整标点。
3. 优先针对具体数值、时间、比例、名称提问（这类问题答案唯一、易于评测）。
4. 问题要用自然的提问方式，像业务人员会问的那样，而不是照抄条款措辞。
5. 如果这条条款过于程序性、没有可提问的实质内容，返回空数组。

输出严格的 JSON 数组，不要任何其他文字：
[{"question": "……？", "answer": "条款中的原文片段"}]

最多产出 2 个问答对。"""

QA_MINE_USER = """【条款出处】{title} {clause_id}

【条款原文】
{clause}

请输出 JSON 数组："""


def build_answer_messages(question: str, context: str) -> list[dict[str, str]]:
    """组装生成答案的消息序列。"""
    return [
        {"role": "system", "content": ANSWER_SYSTEM},
        {"role": "user", "content": ANSWER_USER.format(context=context, question=question)},
    ]


def build_hyde_messages(question: str) -> list[dict[str, str]]:
    return [
        {"role": "system", "content": HYDE_SYSTEM},
        {"role": "user", "content": HYDE_USER.format(question=question)},
    ]


def build_rewrite_messages(question: str, history: str) -> list[dict[str, str]]:
    return [
        {"role": "system", "content": REWRITE_SYSTEM},
        {"role": "user", "content": REWRITE_USER.format(history=history, question=question)},
    ]


def build_qa_mine_messages(clause: str, title: str, clause_id: str) -> list[dict[str, str]]:
    return [
        {"role": "system", "content": QA_MINE_SYSTEM},
        {
            "role": "user",
            "content": QA_MINE_USER.format(clause=clause, title=title, clause_id=clause_id or ""),
        },
    ]
